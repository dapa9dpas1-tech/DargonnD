          The Origin: When Equipment Is Survival
        </h2>
<div class="flex flex-col gap-space-md font-body-md text-body-md text-on-surface-variant">
<p>
            In May 2014, on the exposed granite spines of Denali’s West Buttress at 17,200 feet, an unseasonably ferocious 65-knot gale tore the harness yoke of a conventional commercial mountaineering pack clean off its chassis.
          </p>
<p>
            The climber carrying that compromised pack was DND co-founder Marcus Vance. Forced to lash the load together with 6mm accessory cord and ski straps while frostbite set into his outer knuckles, Vance made a solemn pact right there on the knife-edge ridge: <em>No mountain traveler should ever have their survival compromised by cost-cut plastic hardware or automated production shortcuts.</em>
</p>
<p>
            Returning to Washington state, Vance paired with aerospace composite pattern-maker Elena Rostova. Together in an uninsulated barn loft, they acquired two vintage Juki heavy-duty walking-foot machines, three rolls of olive drab 1000D Cordura, and carved the first anatomical contoured hip-fins from scrap aerospace titanium alloy.
          </p>
</div>
